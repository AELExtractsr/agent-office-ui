// Concatenates office/src/* into dist/office.html and dist/office-html.mjs (string export for Next / Node).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const D = dirname(fileURLToPath(import.meta.url));
const ORDER = ["01_head.html", "02_config.js", "03_scene.js", "04_assemble.js", "05a_avatars.js", "05_runtime.js", "06_ui.js"];
const html = ORDER.map((f) => readFileSync(join(D, "src", f), "utf8")).join("");
mkdirSync(join(D, "dist"), { recursive: true });
writeFileSync(join(D, "dist", "office.html"), html);
writeFileSync(join(D, "dist", "office-html.mjs"), "// generated by office/build.mjs — do not edit\nexport default " + JSON.stringify(html) + ";\n");
console.log("built dist/office.html (" + html.length + " bytes)");
